        val c=context() ?: return ""
        if(args.isEmpty()) return c.getString(id)
        val format=c.getString(id)
        val localized=args.mapIndexed { index,arg -> if(arg is Number && format.contains("%${index+1}\$s")) java.text.NumberFormat.getInstance(locale).format(arg) else arg }.toTypedArray()
        return c.getString(id,*localized)
    }
