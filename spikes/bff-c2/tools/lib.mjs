/**
 * C2 spike runner library — JWT minting (synthetic), HTTP with wall timing,
 * stats helpers. Node-only; no external dependencies.
 */
import { readFileSync } from "node:fs";
import { createSign, createVerify, createHmac } from "node:crypto";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
export const FIX_DIR = process.env.FIXTURES_DIR ?? join(HERE, "..", "fixtures", "generated");
export const WORKER = process.env.WORKER_URL ?? "http://127.0.0.1:8787";
export const STUB = process.env.STUB_URL ?? "http://127.0.0.1:8788";
export const ISSUER = "https://stub.supabase.local/auth/v1";
export const AUDIENCE = "authenticated";
export const ALLOWED_ORIGIN = "https://admin.stub.local";

/** Per-run session secret (regenerated by tools/gen-fixtures.mjs into the
 * gitignored fixtures dir + .dev.vars; never committed, never logged). */
export function sessionSecret() {
  return readFileSync(join(FIX_DIR, "session-secret.txt"), "utf8").trim();
}

const b64url = (buf) => Buffer.from(buf).toString("base64url");

export function mintSupabaseToken({
  keyFile = "private-1.pem",
  kid = "spike-jwk-1",
  iss = ISSUER,
  sub = "spike-admin-1",
  aud = AUDIENCE,
  iat,
  exp,
  alg = "RS256",
} = {}) {
  const priv = readFileSync(join(FIX_DIR, keyFile));
  const now = Math.floor(Date.now() / 1000);
  const header = { alg, typ: "JWT", kid };
  const claims = { iss, sub, aud, iat: iat ?? now, exp: exp ?? now + 900 };
  const data = `${b64url(JSON.stringify(header))}.${b64url(JSON.stringify(claims))}`;
  const sign = createSign("RSA-SHA256");
  sign.update(data);
  return `${data}.${sign.sign(priv, "base64url")}`;
}

/** alg=none forgery attempt (S9). */
export function mintAlgNoneToken(sub = "spike-admin-1") {
  const now = Math.floor(Date.now() / 1000);
  const header = { alg: "none", typ: "JWT", kid: "spike-jwk-1" };
  const claims = { iss: ISSUER, sub, aud: AUDIENCE, iat: now, exp: now + 900 };
  return `${b64url(JSON.stringify(header))}.${b64url(JSON.stringify(claims))}.`;
}

/**
 * Algorithm-confusion attempt (S9): HS256 signature produced with the PUBLIC
 * key material as HMAC secret, while claiming alg RS256.
 */
export function mintConfusedToken() {
  const priv = readFileSync(join(FIX_DIR, "private-1.pem")); // stand-in: sign with known key material
  const now = Math.floor(Date.now() / 1000);
  const header = { alg: "RS256", typ: "JWT", kid: "spike-jwk-1" };
  const claims = { iss: ISSUER, sub: "spike-admin-1", aud: AUDIENCE, iat: now, exp: now + 900 };
  const data = `${b64url(JSON.stringify(header))}.${b64url(JSON.stringify(claims))}`;
  const hmac = createHmac("sha256", priv).update(data).digest("base64url");
  return `${data}.${hmac}`;
}

export function mintSidToken({ sid = "s-any", sub = "spike-admin-1", expOffset = 900, secret } = {}) {
  const key = secret ?? sessionSecret();
  const now = Math.floor(Date.now() / 1000);
  const header = { alg: "HS256", typ: "JWT" };
  const claims = { sid, sub, exp: now + expOffset };
  const data = `${b64url(JSON.stringify(header))}.${b64url(JSON.stringify(claims))}`;
  const sig = createHmac("sha256", key).update(data).digest("base64url");
  return `${data}.${sig}`;
}

/** HTTP request with client-side wall-clock timing. Returns parsed result. */
export async function req(base, path, { method = "GET", headers = {}, body, cookie } = {}) {
  const h = new Headers(headers);
  if (cookie) h.set("Cookie", cookie);
  if (body !== undefined) h.set("Content-Type", "application/json");
  const t0 = performance.now();
  let res;
  try {
    res = await fetch(base + path, { method, headers: h, body: body !== undefined ? JSON.stringify(body) : undefined });
  } catch (e) {
    return { status: 0, error: String(e), wallMs: performance.now() - t0, headers: {}, body: null };
  }
  const text = await res.text();
  const wallMs = performance.now() - t0;
  const cpuHeader = res.headers.get("x-spike-cpu-ms");
  let json = null;
  try {
    json = JSON.parse(text);
  } catch {
    /* non-JSON */
  }
  return {
    status: res.status,
    headers: Object.fromEntries(res.headers.entries()),
    setCookie: res.headers.getSetCookie?.() ?? [],
    body: json,
    text,
    cpuMs: cpuHeader === null ? null : Number(cpuHeader),
    wallMs,
  };
}

export async function control(cmd) {
  return req(STUB, "/__control", { method: "POST", body: cmd });
}

export async function stubState() {
  const r = await req(STUB, "/__state");
  return r.body;
}

/** Sign in via the BFF handover; returns cookie/csrf handles for a subject. */
export async function signIn(sub, tokenOpts = {}) {
  const token = mintSupabaseToken({ sub, ...tokenOpts });
  const r = await req(WORKER, "/v1/session", {
    method: "POST",
    headers: { Origin: ALLOWED_ORIGIN },
    body: { access_token: token },
  });
  if (r.status !== 200) return { status: r.status, result: r };
  const sid = r.setCookie.find((c) => c.startsWith("sid="))?.split(";")[0];
  const csrf = r.setCookie.find((c) => c.startsWith("csrf="))?.split(";")[0]?.split("=")[1];
  return { status: 200, cookie: `${sid}; ${csrf ? `csrf=${csrf}` : ""}`, csrf, result: r };
}

export function percentiles(values, ps = [0.5, 0.95, 0.99]) {
  const sorted = [...values].sort((a, b) => a - b);
  const out = {};
  for (const p of ps) {
    const idx = Math.max(0, Math.ceil(p * sorted.length) - 1);
    out[`p${Math.round(p * 100)}`] = sorted[idx] ?? null;
  }
  out.max = sorted[sorted.length - 1] ?? null;
  out.min = sorted[0] ?? null;
  out.n = sorted.length;
  return out;
}

export function median(values) {
  return percentiles(values, [0.5]).p50;
}
